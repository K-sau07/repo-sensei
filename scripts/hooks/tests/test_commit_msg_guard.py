from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from types import ModuleType

import pytest

HOOKS_DIR = Path(__file__).resolve().parents[1]


def _load(name: str) -> ModuleType:
    if str(HOOKS_DIR) not in sys.path:
        sys.path.insert(0, str(HOOKS_DIR))
    spec = importlib.util.spec_from_file_location(name, HOOKS_DIR / f"{name}.py")
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


guard = _load("commit_msg_guard")
push_guard = _load("pre_push_guard")


@pytest.mark.parametrize(
    "message",
    [
        "feat(api): 0.7 app factory, request ids and health checks",
        "chore(repo): 0.1 toolchain pins and repo hygiene",
        "fix(engine): 1.16 speed up discovery on large repos",
        "feat(engine): A.1 example improvement",
        "feat(mcp): 7.5 setup instructions for Claude Code and Cursor",
        "build(repo): 0.2 python workspace\n\n- created packages\n- added lockfile",
        "Merge pull request #12 from K-sau07/p0-foundations",
        "Merge branch 'main' into feature",
        'Revert "feat(api): 0.7 app factory"',
        "feat(api): 0.7 app factory\n# Please enter the commit message for your changes.",
    ],
)
def test_accepts_valid_messages(message: str) -> None:
    assert guard.check_message(message) == []


@pytest.mark.parametrize(
    "message",
    [
        "",
        "test",
        "update stuff",
        "feat: 0.7 missing scope",
        "feat(api): app factory without a step number",
        "Feat(api): 0.7 wrong type casing",
        "feat(API): 0.7 uppercase scope",
        "wip(api): 0.7 unknown type",
        "Merge stuff without format",
        "Revert everything",
    ],
)
def test_rejects_bad_format(message: str) -> None:
    assert guard.check_message(message) != []


@pytest.mark.parametrize(
    "trailer",
    [
        "Co-Authored-By: Someone <someone@example.com>",
        "co-authored-by: bot <bot@example.com>",
        "Co\u2010authored-by: unicode hyphen <x@y.z>",
        "Co authored by: spaced <x@y.z>",
        "Co-developed-by: someone <x@y.z>",
        "Assisted-by: a tool",
        "Generated with SomeTool",
        "Generated  with two spaces",
        "Generated-by: a tool",
        "generated by an assistant",
        "AI generated change",
        "This change is AI-generated",
        "Made with Claude Code",
        "Written by AI",
        "Signed: <noreply@anthropic.com>",
        "\N{ROBOT FACE} done",
    ],
)
def test_rejects_attribution(trailer: str) -> None:
    problems = guard.check_message(f"feat(api): 0.7 app factory\n\n{trailer}")
    assert any("attribution" in problem for problem in problems)


def test_rejects_attribution_hidden_in_hash_lines() -> None:
    # `git commit -m` keeps lines starting with '#', so they must be scanned too.
    message = "feat(api): 0.7 app factory\n\n# Generated with an AI tool"
    assert any("attribution" in p for p in guard.check_message(message))


def test_ignores_verbose_diff_below_scissors() -> None:
    message = f"feat(api): 0.7 app factory\n{guard.SCISSORS}\n+ generated by tool in a diff"
    assert guard.check_message(message) == []


def test_author_check() -> None:
    assert guard.check_author("kashyap.sau@northeastern.edu") == []
    assert guard.check_author("Kashyap.Sau@Northeastern.edu") == []
    assert guard.check_author("someone@else.com") != []
    assert guard.check_author("") != []


def test_author_email_cannot_be_overridden_by_environment(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("SENSEI_EXPECTED_AUTHOR_EMAIL", "someone@else.com")
    reloaded = _load("commit_msg_guard")
    assert reloaded.check_author("someone@else.com") != []


def test_main_rejects_and_accepts(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(guard, "author_email", lambda: "kashyap.sau@northeastern.edu")
    good = tmp_path / "good"
    good.write_text("feat(api): 0.7 app factory\n", encoding="utf-8")
    bad = tmp_path / "bad"
    bad.write_text("feat(api): 0.7 x\n\nCo-Authored-By: x <x@y.z>\n", encoding="utf-8")
    assert guard.main(["guard", str(good)]) == 0
    assert guard.main(["guard", str(bad)]) == 1


