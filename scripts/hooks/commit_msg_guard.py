"""commit-msg hook: enforce the commit convention and authorship rules.

Rules:
  1. Message subject must look like ``<type>(<scope>): <step> <summary>``,
     for example ``feat(api): 0.7 app factory and health checks``.
  2. No attribution trailers or "generated by" lines of any kind.
  3. The commit author email must match the expected owner email.

Usage (from pre-commit): ``commit_msg_guard.py <path-to-COMMIT_EDITMSG>``.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

EXPECTED_AUTHOR_EMAIL = os.environ.get(
    "SENSEI_EXPECTED_AUTHOR_EMAIL", "kashyap.sau@northeastern.edu"
)

SUBJECT_RE = re.compile(
    r"^(feat|fix|chore|refactor|test|docs|build|ci|perf)"
    r"\([a-z0-9-]+\): "
    r"(\d+|A)\.\d+ "
    r"\S.*$"
)
ALLOWED_PREFIXES = ("Merge ", "Revert ")

FORBIDDEN_PATTERNS = (
    re.compile(r"co-authored-by\s*:", re.IGNORECASE),
    re.compile(r"generated (with|by)\b", re.IGNORECASE),
    re.compile(r"noreply@anthropic\.com", re.IGNORECASE),
    re.compile(r"ai-generated", re.IGNORECASE),
    re.compile("\N{ROBOT FACE}"),
)


def clean_message(raw: str) -> str:
    """Drop git comment lines and surrounding whitespace."""
    lines = [line for line in raw.splitlines() if not line.startswith("#")]
    return "\n".join(lines).strip()


def check_message(message: str) -> list[str]:
    """Return a list of human-readable problems with the commit message."""
    problems: list[str] = []
    if not message:
        return ["commit message is empty"]

    subject = message.splitlines()[0]
    if not subject.startswith(ALLOWED_PREFIXES) and not SUBJECT_RE.match(subject):
        problems.append(
            "subject must match '<type>(<scope>): <step> <summary>', "
            "e.g. 'feat(api): 0.7 app factory and health checks'"
        )

    for pattern in FORBIDDEN_PATTERNS:
        if pattern.search(message):
            problems.append(f"attribution text is not allowed (matched {pattern.pattern!r})")
    return problems


def author_email() -> str:
    ident = subprocess.run(
        ["git", "var", "GIT_AUTHOR_IDENT"],  # noqa: S607 - git resolved from PATH
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    match = re.search(r"<([^>]+)>", ident)
    return match.group(1) if match else ""


def check_author(email: str) -> list[str]:
    if email.lower() != EXPECTED_AUTHOR_EMAIL.lower():
        return [f"commit author email must be {EXPECTED_AUTHOR_EMAIL}, got {email or 'nothing'}"]
    return []


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        sys.stderr.write("usage: commit_msg_guard.py <commit-msg-file>\n")
        return 2
    message = clean_message(Path(argv[1]).read_text(encoding="utf-8"))
    problems = check_message(message) + check_author(author_email())
    if problems:
        sys.stderr.write("commit rejected:\n")
        for problem in problems:
            sys.stderr.write(f"  - {problem}\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
