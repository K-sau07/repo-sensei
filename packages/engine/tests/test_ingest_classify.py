"""Classifying files: language, hashes, line counts and the binary/generated/vendored/too-large
flags."""

from __future__ import annotations

import errno
import hashlib
from pathlib import Path

import pytest

from sensei_engine.ingest.classify import MAX_PARSE_BYTES, FileFacts, Flag, classify
from sensei_engine.ingest.ignore import Attribute
from sensei_engine.ingest.languages import detect_language
from sensei_engine.ingest.walk import WalkedFile

LFS_POINTER = (
    b"version https://git-lfs.github.com/spec/v1\n"
    b"oid sha256:4d7a214614ab2935c943f9e0ff69d22eadbb8f32b1258daaa5e2ca24d17e2393\n"
    b"size 12345\n"
)


def _file(
    tmp_path: Path,
    path: str,
    content: bytes,
    attributes: frozenset[Attribute] = frozenset(),
) -> FileFacts:
    target = tmp_path / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(content)
    return classify(WalkedFile(path, target, len(content), attributes))


def test_hashes_and_lines(tmp_path: Path) -> None:
    content = b"import os\n\nprint(os.name)\n"
    facts = _file(tmp_path, "src/app.py", content)
    # git hash-object: sha1 over "blob <size>\0" + content.
    blob = hashlib.sha1(b"blob %d\0" % len(content) + content, usedforsecurity=False)
    assert facts.blob_sha == blob.hexdigest()
    assert facts.content_hash == hashlib.sha256(content).digest()
    assert (facts.language, facts.loc, facts.size, facts.flags) == ("python", 3, 26, frozenset())
    assert facts.text == content.decode()


@pytest.mark.parametrize(
    ("content", "loc"), [(b"", 0), (b"one", 1), (b"one\n", 1), (b"a\nb", 2), (b"\n\n", 2)]
)
def test_physical_lines(tmp_path: Path, content: bytes, loc: int) -> None:
    assert _file(tmp_path, "a.txt", content).loc == loc


def test_binary_files(tmp_path: Path) -> None:
    png = _file(tmp_path, "logo.png", b"not even a real png")  # known binary by name
    nul = _file(tmp_path, "data.dat", b"abc\0def")
    for facts in (png, nul):
        assert Flag.BINARY in facts.flags
        assert (facts.language, facts.loc, facts.text) == (None, None, None)
    assert len(png.content_hash) == 32  # hashed all the same


def test_text_in_another_encoding_is_text(tmp_path: Path) -> None:
    content = "# Résumé générique, déjà vu, über naïve café\n".encode("latin-1") * 20
    facts = _file(tmp_path, "notes.py", content)
    assert Flag.BINARY not in facts.flags
    assert facts.loc == 20
    assert facts.text is not None
    assert "café" in facts.text


def test_a_utf8_bom_is_dropped(tmp_path: Path) -> None:
    assert _file(tmp_path, "a.py", b"\xef\xbb\xbfx = 1\n").text == "x = 1\n"


def test_large_files_are_hashed_but_not_read(tmp_path: Path) -> None:
    content = b"x = 1\n" * (MAX_PARSE_BYTES // 6 + 10)
    facts = _file(tmp_path, "big.py", content)
    assert facts.flags == {Flag.TOO_LARGE}
    assert (facts.loc, facts.text, facts.language) == (None, None, "python")
    assert facts.content_hash == hashlib.sha256(content).digest()
    big_binary = _file(tmp_path, "big.bin", b"\0" * (MAX_PARSE_BYTES + 1))
    assert big_binary.flags == {Flag.TOO_LARGE, Flag.BINARY}


@pytest.mark.parametrize(
    ("path", "content"),
    [
        ("client.ts", b"// This file is auto-generated by @hey-api/openapi-ts\nexport {}\n"),
        ("models.go", b"// Code generated by sqlc. DO NOT EDIT.\npackage db\n"),
        ("Schema.java", b"/*\n * @generated by thrift\n */\nclass Schema {}\n"),
        ("x.py", b'"""Automatically generated from the schema."""\nX = 1\n'),
        ("api_pb2.py", b"X = 1\n"),
        ("routeTree.gen.ts", b"export {}\n"),
        ("theme.min.css", b"a{}\n"),
        ("plain.ts", b"export {}\n"),
    ],
)
def test_generated_files(tmp_path: Path, path: str, content: bytes) -> None:
    expected = path != "plain.ts"
    assert (Flag.GENERATED in _file(tmp_path, path, content).flags) is expected


def test_generated_markers_count_only_in_header_comments(tmp_path: Path) -> None:
    prose = b"# Our API\n\nThe client is auto-generated from the OpenAPI schema.\n"
    assert Flag.GENERATED not in _file(tmp_path, "README.md", prose).flags
    late = b"x = 1\n" * 40 + b"# DO NOT EDIT below this line\n"
    assert Flag.GENERATED not in _file(tmp_path, "late.py", late).flags
    in_code = b'MESSAGE = "this file is auto-generated"\n'
    assert Flag.GENERATED not in _file(tmp_path, "msg.py", in_code).flags


def test_linguist_attributes_set_flags(tmp_path: Path) -> None:
    generated = _file(tmp_path, "schema.d.ts", b"export {}\n", frozenset({Attribute.GENERATED}))
    vendored = _file(tmp_path, "lib/x.js", b"1\n", frozenset({Attribute.VENDORED}))
    docs = _file(tmp_path, "guide/x.md", b"# x\n", frozenset({Attribute.DOCUMENTATION}))
    assert generated.flags == {Flag.GENERATED}
    assert vendored.flags == {Flag.VENDORED}
    assert docs.flags == {Flag.DOCUMENTATION}


@pytest.mark.parametrize(
    "path", ["third_party/lib.c", "src/External/x.py", "pkg/_vendor/six.py", "vendored/a.js"]
)
def test_vendored_directories(tmp_path: Path, path: str) -> None:
    assert Flag.VENDORED in _file(tmp_path, path, b"1\n").flags


def test_lfs_pointers(tmp_path: Path) -> None:
    facts = _file(tmp_path, "model.bin", LFS_POINTER)
    assert Flag.LFS_POINTER in facts.flags
    assert Flag.BINARY not in facts.flags


def test_a_symlink_swapped_in_is_not_followed(tmp_path: Path) -> None:
    secret = tmp_path / "secret.txt"
    secret.write_text("s3cret")
    link = tmp_path / "a.txt"
    link.symlink_to(secret)
    with pytest.raises(OSError, match="symbolic links") as exc:
        classify(WalkedFile("a.txt", link, 6, frozenset()))
    assert exc.value.errno == errno.ELOOP


