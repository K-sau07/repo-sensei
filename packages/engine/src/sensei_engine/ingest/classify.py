"""What a file is: its language, hashes, line count and flags.

Flags:

- ``binary``: a NUL byte in the first 8 KB (UTF-16 and UTF-32 text with a byte order mark is
  text), a name ``identify`` knows as binary, or bytes no text encoding explains;
- ``generated``: a generator's marker in a comment near the top ("@generated", "auto-generated
  by …", "DO NOT EDIT" with "generated"), a generated-file name (``*_pb2.py``, ``*.gen.ts``,
  ``*.min.css``), minified JavaScript or CSS (lines over 110 characters on average) or
  ``linguist-generated``;
- ``vendored``: under a third-party directory or ``linguist-vendored``;
- ``too_large``: over 1 MB; recorded and hashed, never parsed;
- ``lfs_pointer``: a Git LFS pointer (the content isn't fetched);
- ``documentation``: ``linguist-documentation``.

The file is opened without following symbolic links (``O_NOFOLLOW``), so a link swapped in after
the walk can't make indexing read outside the tree.
"""

from __future__ import annotations

import codecs
import enum
import hashlib
import os
import re
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

import xxhash
from charset_normalizer import from_bytes
from identify import identify

from sensei_engine.ingest.ignore import Attribute
from sensei_engine.ingest.languages import detect_language
from sensei_engine.ingest.walk import WalkedFile

MAX_PARSE_BYTES = 1024 * 1024  # bigger files are too_large
SAMPLE_BYTES = 8 * 1024
HEADER_BYTES = 2 * 1024  # generator markers are looked for in the first lines of this
CHUNK_BYTES = 1024 * 1024

LFS_POINTER_PREFIX = b"version https://git-lfs.github.com/spec/v1\n"
LFS_POINTER_MAX_BYTES = 1024


class Flag(enum.StrEnum):
    BINARY = "binary"
    GENERATED = "generated"
    VENDORED = "vendored"
    TOO_LARGE = "too_large"
    LFS_POINTER = "lfs_pointer"
    DOCUMENTATION = "documentation"


# A generator's marker in a comment near the top of the file. Specific phrases only: plenty of
# hand-written comments say "auto-generated" (ids) or "do not edit" (warnings).
_COMMENT = re.compile(r"^\s*(?:#|//|/\*|\*|<!--|--|;|%|\"\"\"|\'\'\'|\{\{!?--)")
_GENERATED_LINE = re.compile(
    r"@generated\b"
    # The comment opens with it, about the file: "This file was automatically generated by …",
    # "Auto-generated from schema.json" (not "the id is auto-generated by Postgres").
    r"|^\s*(?:#|//|/\*|\*|<!--|--|;|%|\"\"\"|\'\'\'|\{\{!?--)[\s*#/!-]*"
    r"(?i:(?:this (?:file|code|module) (?:is|was|has been) )?"
    r"(?:auto-?generated|automatically generated|machine generated|generated)\s+"
    r"(?:by|from|with|using)\b)"
    r"|(?i:\bgenerated by (?:the )?(?:protoc|protobuf|openapi|swagger|thrift|graphql-codegen|"
    r"prisma|sqlc|mockery|mockgen|stringer|cython|flatc|buf)\b)"
)
_DO_NOT_EDIT = re.compile(r"\bDO NOT EDIT\b")  # counts together with "generated" (Go's style)
_GENERATED_WORD = re.compile(r"(?i:\bgenerat(?:ed|or)\b)")
HEADER_LINES = 15
MINIFIED_LINE_LENGTH = 110  # average characters per line, as GitHub's Linguist
MINIFIED_MIN_BYTES = 1000
_GENERATED_NAMES = re.compile(
    r"(?:_pb2(?:_grpc)?\.pyi?|\.pb\.(?:go|cc|h|swift)|_pb\.(?:js|ts|d\.ts)|_grpc_pb\.(?:js|d\.ts)"
    r"|\.gen\.[a-z]+|\.generated\.[a-z]+|\.g\.dart|\.freezed\.dart|\.designer\.cs"
    r"|\.min\.css|-lock\.json)$"
)
VENDORED_DIRS = frozenset(
    {
        "third_party",
        "third-party",
        "thirdparty",
        "3rdparty",
        "3rd_party",
        "3rd-party",
        "vendors",
        "vendored",
        "_vendor",
        "extern",
        "external",
    }
)


@dataclass(frozen=True, slots=True)
class FileFacts:
    path: str
    size: int
    blob_sha: str  # git's id for the content (sha1 of "blob <size>\0" + content)
    content_hash: bytes  # SHA-256 of the content
    fast_hash: bytes  # xxh3-128 of the content (quick comparisons)
    language: str | None
    loc: int | None  # physical lines; None for binary and too-large files
    flags: frozenset[Flag]
    # The content as text, for the role heuristics; None for binary and too-large files.
    text: str | None


class FileChangedError(Exception):
    """The file changed while it was being read (the tree isn't stable)."""


@dataclass(frozen=True, slots=True)
class _Read:
    head: bytes  # up to MAX_PARSE_BYTES + 1 bytes
    blob_sha: str
    sha256: bytes
    xxh3: bytes
    size: int


def _read(path: Path) -> _Read:
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | getattr(os, "O_CLOEXEC", 0))
    with os.fdopen(fd, "rb") as handle:
        size = os.fstat(handle.fileno()).st_size
        blob = hashlib.sha1(f"blob {size}\0".encode(), usedforsecurity=False)
        sha256 = hashlib.sha256()
        xxh3 = xxhash.xxh3_128()
        head = bytearray()
        read = 0
        while chunk := handle.read(CHUNK_BYTES):
            read += len(chunk)
            blob.update(chunk)
            sha256.update(chunk)
            xxh3.update(chunk)
            if len(head) <= MAX_PARSE_BYTES:
                head += chunk[: MAX_PARSE_BYTES + 1 - len(head)]
    if read != size:
        raise FileChangedError(str(path))
    return _Read(bytes(head), blob.hexdigest(), sha256.digest(), xxh3.digest(), size)


_UNICODE_BOMS = (  # UTF-32 first: its little-endian mark starts with UTF-16's
    (codecs.BOM_UTF32_LE, "utf-32"),
    (codecs.BOM_UTF32_BE, "utf-32"),
    (codecs.BOM_UTF16_LE, "utf-16"),
    (codecs.BOM_UTF16_BE, "utf-16"),
)


def _wide_encoding(head: bytes) -> str | None:
    """UTF-16 or UTF-32 by byte order mark: text, even though it is full of NUL bytes."""
    return next((encoding for bom, encoding in _UNICODE_BOMS if head.startswith(bom)), None)


def decode_text(data: bytes) -> tuple[str, str] | None:
    """``(text, encoding)``, or None if no text encoding explains the bytes (binary)."""
    wide = _wide_encoding(data)
    if wide is not None:
        return data.decode(wide, "replace"), wide
    if b"\0" in data[:SAMPLE_BYTES]:
        return None
    try:
        return codecs.decode(data, "utf-8-sig"), "utf-8"
    except UnicodeDecodeError:
        pass
    best = from_bytes(data[:SAMPLE_BYTES]).best()
    return None if best is None else (data.decode(best.encoding, "replace"), best.encoding)


def _decode(data: bytes) -> str | None:
    decoded = decode_text(data)
    return None if decoded is None else decoded[0]


def _is_text_sample(sample: bytes) -> bool:
    """For files too large to decode whole: does the start read as text?"""
    try:
        codecs.getincrementaldecoder("utf-8")().decode(sample, final=False)
    except UnicodeDecodeError:
        return from_bytes(sample).best() is not None
    return True


def _lines(text: str) -> int:
    if not text:
        return 0
    return text.count("\n") + (0 if text.endswith("\n") else 1)


def _has_generated_marker(text: str) -> bool:
    comments = [
        line for line in text[:HEADER_BYTES].splitlines()[:HEADER_LINES] if _COMMENT.match(line)
    ]
    if any(_GENERATED_LINE.search(line) for line in comments):
        return True
    header = "\n".join(comments)
    return bool(_DO_NOT_EDIT.search(header) and _GENERATED_WORD.search(header))


def _minified(language: str | None, text: str, size: int) -> bool:
    if language not in ("javascript", "css") or size < MINIFIED_MIN_BYTES:
        return False
    return size / max(_lines(text), 1) > MINIFIED_LINE_LENGTH


def classify(walked: WalkedFile) -> FileFacts:
    read = _read(walked.absolute)
    head, size = read.head, read.size
    flags: set[Flag] = set()
    name = PurePosixPath(walked.path).name
    tags = identify.tags_from_filename(name)
    text: str | None = None
    wide = _wide_encoding(head)
    if "binary" in tags or (wide is None and b"\0" in head[:SAMPLE_BYTES]):
        flags.add(Flag.BINARY)
    elif size > MAX_PARSE_BYTES:
        if wide is None and not _is_text_sample(head[:SAMPLE_BYTES]):
            flags.add(Flag.BINARY)
    else:
        text = _decode(head)
        if text is None:
            flags.add(Flag.BINARY)
    if size > MAX_PARSE_BYTES:
        flags.add(Flag.TOO_LARGE)
    if size <= LFS_POINTER_MAX_BYTES and head.startswith(LFS_POINTER_PREFIX):
        flags.add(Flag.LFS_POINTER)
        flags.discard(Flag.BINARY)
    language = None if Flag.BINARY in flags else detect_language(walked.path, head[:256])
    if (
        Attribute.GENERATED in walked.attributes
        or _GENERATED_NAMES.search(name)
        or (text is not None and (_has_generated_marker(text) or _minified(language, text, size)))
    ):
        flags.add(Flag.GENERATED)
    parts = PurePosixPath(walked.path).parts[:-1]
    if Attribute.VENDORED in walked.attributes or VENDORED_DIRS.intersection(
        part.lower() for part in parts
    ):
        flags.add(Flag.VENDORED)
    if Attribute.DOCUMENTATION in walked.attributes:
        flags.add(Flag.DOCUMENTATION)
    return FileFacts(
        path=walked.path,
        size=size,
        blob_sha=read.blob_sha,
        content_hash=read.sha256,
        fast_hash=read.xxh3,
        language=language,
        loc=None if text is None else _lines(text),
        flags=frozenset(flags),
        text=text,
    )
